// 获取翻译文本的辅助函数
export const t = (key, language = 'en') => {
  const keys = key.split('.');
  let value = translations[language];
  
  for (const k of keys) {
    if (value && value[k]) {
      value = value[k];
    } else {
      // 如果找不到翻译，返回英文版本
      value = translations.en;
      for (const k2 of keys) {
        if (value && value[k2]) {
          value = value[k2];
        } else {
          return key; // 如果连英文都没有，返回键名
        }
      }
      break;
    }
  }
  
  return value || key;
}; 